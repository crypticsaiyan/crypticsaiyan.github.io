#!/usr/bin/env python3
"""Build a Font Awesome subset containing only the icons used in src/.

The full Font Awesome CSS + fonts are ~300 KB; the site uses ~40 icons.
Re-run after adding or removing an icon (needs fonttools + brotli):

    npm run icons
"""
import re
from pathlib import Path

from fontTools import subset

ROOT = Path(__file__).resolve().parent.parent
FA = ROOT / "node_modules/@fortawesome/fontawesome-free"
CSS_OUT = ROOT / "src/fontawesome-subset.css"
FONT_OUT = ROOT / "public/assets/fonts"
FONT_URL = "/assets/fonts"
FONTS = ["fa-solid-900.woff2", "fa-brands-400.woff2"]

ICON_RULE = re.compile(r'([^{}]+)\{\s*--fa:\s*"([^"]*)"\s*;?\s*\}')


def icon_map(css):
    icons = {}
    for selectors, value in ICON_RULE.findall(css):
        for selector in selectors.split(","):
            selector = selector.strip()
            if re.fullmatch(r"\.fa-[a-z0-9-]+", selector):
                icons[selector[1:]] = value
    return icons


def codepoint(value):
    return int(value[1:], 16) if value.startswith("\\") else ord(value)


def used_classes():
    found = set()
    for path in (ROOT / "src").rglob("*"):
        if path.suffix in {".js", ".jsx"} and "concepts" not in path.parts:
            found |= set(re.findall(r"fa-[a-z0-9-]+", path.read_text()))
    return found


def main():
    core = (FA / "css/fontawesome.css").read_text()
    solid = (FA / "css/solid.css").read_text()
    brands = (FA / "css/brands.css").read_text()

    icons = icon_map(core) | icon_map(brands)
    used = sorted(name for name in used_classes() if name in icons)

    # base .fa/.fas/.fab rules only; utilities (.fa-2x, .fa-spin, ...) are unused
    base = core[core.index("*/") + 2 : core.index(".fa-1x {")].strip()
    styles = [ICON_RULE.sub("", css).split("*/", 1)[1].strip() for css in (solid, brands)]
    rules = "\n".join(f'.{name} {{ --fa: "{icons[name]}"; }}' for name in used)

    css = "\n\n".join(
        [
            "/* Generated by scripts/fa-subset.py from @fortawesome/fontawesome-free."
            " Do not edit. */",
            base,
            *styles,
            "/* keep Font Awesome 6's natural icon widths (v7 defaults to fixed) */\n"
            ":root { --fa-width: auto; }",
            rules,
        ]
    )
    css = re.sub(r'url\("\.\./webfonts/([^"]+)"\)', rf'url("{FONT_URL}/\1")', css)
    CSS_OUT.write_text(re.sub(r"\n{3,}", "\n\n", css) + "\n")

    unicodes = {codepoint(icons[name]) for name in used}
    FONT_OUT.mkdir(parents=True, exist_ok=True)
    for font in FONTS:
        options = subset.Options()
        options.flavor = "woff2"
        options.layout_features = []
        options.notdef_outline = True
        loaded = subset.load_font(str(FA / "webfonts" / font), options)
        subsetter = subset.Subsetter(options)
        subsetter.populate(unicodes=unicodes)
        subsetter.subset(loaded)
        subset.save_font(loaded, str(FONT_OUT / font), options)

    print(f"{len(used)} icons -> {CSS_OUT.relative_to(ROOT)}, {FONT_OUT.relative_to(ROOT)}/")


if __name__ == "__main__":
    main()
